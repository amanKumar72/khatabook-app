import * as FileSystem from 'expo-file-system/legacy';
import * as Sharing from 'expo-sharing';
import * as DocumentPicker from 'expo-document-picker';
import * as Crypto from 'expo-crypto';
import { getDatabase } from '../db/database';
import { BackupArchive, Book, Customer, Transaction, Bill, BillItem, InventoryItem, CashbookEntry, Staff, StaffAttendance } from '../types/models';

export interface RestoreResult {
  success: boolean;
  message: string;
  counts?: {
    books: number;
    customers: number;
    transactions: number;
    bills: number;
    cashbook: number;
    staff: number;
    attachments: number;
  };
}

export class BackupEngine {
  /**
   * Export all database records and media attachments into a single backup JSON file
   */
  static async exportCompleteData(): Promise<string> {
    const db = await getDatabase();

    // 1. Extract all table records
    const tables = {
      books: await db.getAllAsync<Book>('SELECT * FROM books'),
      customers: await db.getAllAsync<Customer>('SELECT * FROM customers'),
      transactions: await db.getAllAsync<Transaction>('SELECT * FROM transactions'),
      bills: await db.getAllAsync<Bill>('SELECT * FROM bills'),
      bill_items: await db.getAllAsync<BillItem>('SELECT * FROM bill_items'),
      inventory_items: await db.getAllAsync<InventoryItem>('SELECT * FROM inventory_items'),
      cashbook: await db.getAllAsync<CashbookEntry>('SELECT * FROM cashbook'),
      staff: await db.getAllAsync<Staff>('SELECT * FROM staff'),
      staff_attendance: await db.getAllAsync<StaffAttendance>('SELECT * FROM staff_attendance'),
    };

    // 2. Package attachments from local storage
    const attachments: { filename: string; base64: string }[] = [];
    const attachmentsDir = `${FileSystem.documentDirectory}attachments/`;
    const dirInfo = await FileSystem.getInfoAsync(attachmentsDir);

    if (dirInfo.exists) {
      const files = await FileSystem.readDirectoryAsync(attachmentsDir);
      for (const file of files) {
        try {
          const fileContent = await FileSystem.readAsStringAsync(`${attachmentsDir}${file}`, {
            encoding: FileSystem.EncodingType.Base64,
          });
          attachments.push({ filename: file, base64: fileContent });
        } catch (e) {
          console.warn(`Failed to read attachment ${file}:`, e);
        }
      }
    }

    // 3. Compute Checksum across tables payload
    const rawDataString = JSON.stringify(tables);
    const checksum = await Crypto.digestStringAsync(Crypto.CryptoDigestAlgorithm.SHA256, rawDataString);

    const archive: BackupArchive = {
      app: 'KhatabookOffline',
      version: 1,
      exportedAt: new Date().toISOString(),
      checksum,
      tables,
      attachments,
    };

    // 4. Save to cache directory and trigger native Share Sheet
    const filename = `khatabook_backup_${Date.now()}.json`;
    const exportPath = `${FileSystem.cacheDirectory}${filename}`;
    await FileSystem.writeAsStringAsync(exportPath, JSON.stringify(archive, null, 2), {
      encoding: FileSystem.EncodingType.UTF8,
    });

    if (await Sharing.isAvailableAsync()) {
      await Sharing.shareAsync(exportPath, {
        mimeType: 'application/json',
        dialogTitle: 'Export Khatabook Backup',
        UTI: 'public.json',
      });
    }

    return exportPath;
  }

  /**
   * Import a backup file and restore complete data atomically
   */
  static async importCompleteData(): Promise<RestoreResult> {
    // 1. Pick backup file
    const result = await DocumentPicker.getDocumentAsync({
      type: 'application/json',
      copyToCacheDirectory: true,
    });

    if (result.canceled || !result.assets || result.assets.length === 0) {
      return { success: false, message: 'Backup import canceled by user.' };
    }

    const fileUri = result.assets[0].uri;
    const content = await FileSystem.readAsStringAsync(fileUri, {
      encoding: FileSystem.EncodingType.UTF8,
    });

    // 2. Parse & Validate Signature
    let archive: BackupArchive;
    try {
      archive = JSON.parse(content);
    } catch {
      return { success: false, message: 'Invalid backup file format. Must be a valid JSON file.' };
    }

    if (archive.app !== 'KhatabookOffline' || !archive.tables) {
      return { success: false, message: 'Unrecognized Khatabook backup file. Ensure the file was generated by Khatabook.' };
    }

    // 3. Verify Checksum
    const recalculated = await Crypto.digestStringAsync(
      Crypto.CryptoDigestAlgorithm.SHA256,
      JSON.stringify(archive.tables)
    );

    if (recalculated !== archive.checksum) {
      return { success: false, message: 'Backup verification failed: checksum mismatch (corrupted or modified file).' };
    }

    // 4. Atomic Database Restoration inside Transaction
    const db = await getDatabase();
    await db.withTransactionAsync(async () => {
      // Clear existing records
      await db.execAsync(`
        DELETE FROM staff_attendance;
        DELETE FROM staff;
        DELETE FROM cashbook;
        DELETE FROM inventory_items;
        DELETE FROM bill_items;
        DELETE FROM bills;
        DELETE FROM transactions;
        DELETE FROM customers;
        DELETE FROM books;
      `);

      // Bulk Insert Books
      for (const b of archive.tables.books || []) {
        await db.runAsync(
          'INSERT INTO books (id, name, phone, currency, business_category, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?)',
          [b.id, b.name, b.phone || '', b.currency || 'INR', b.business_category || '', b.created_at, b.updated_at]
        );
      }

      // Bulk Insert Customers
      for (const c of archive.tables.customers || []) {
        await db.runAsync(
          'INSERT INTO customers (id, book_id, name, phone, party_type, balance, credit_limit, address, gstin, is_archived, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)',
          [c.id, c.book_id, c.name, c.phone || '', c.party_type, c.balance, c.credit_limit || 0, c.address || '', c.gstin || '', c.is_archived || 0, c.created_at, c.updated_at]
        );
      }

      // Bulk Insert Transactions
      for (const t of archive.tables.transactions || []) {
        await db.runAsync(
          'INSERT INTO transactions (id, book_id, customer_id, amount, type, date, description, attachment_uri, due_date, is_deleted, created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)',
          [t.id, t.book_id, t.customer_id, t.amount, t.type, t.date, t.description || '', t.attachment_uri || '', t.due_date || '', t.is_deleted || 0, t.created_at, t.updated_at]
        );
      }

      // Bulk Insert Bills & Items
      for (const b of archive.tables.bills || []) {
        await db.runAsync(
          'INSERT INTO bills (id, book_id, customer_id, customer_name, bill_number, bill_date, bill_type, subtotal, tax_total, discount, total_amount, payment_mode, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)',
          [b.id, b.book_id, b.customer_id || '', b.customer_name || '', b.bill_number, b.bill_date, b.bill_type, b.subtotal, b.tax_total, b.discount, b.total_amount, b.payment_mode, b.created_at]
        );
      }
      for (const bi of archive.tables.bill_items || []) {
        await db.runAsync(
          'INSERT INTO bill_items (id, bill_id, item_name, quantity, unit, rate, tax_percentage, amount) VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
          [bi.id, bi.bill_id, bi.item_name, bi.quantity, bi.unit, bi.rate, bi.tax_percentage, bi.amount]
        );
      }

      // Bulk Insert Inventory
      for (const inv of archive.tables.inventory_items || []) {
        await db.runAsync(
          'INSERT INTO inventory_items (id, book_id, name, barcode, unit, purchase_price, sale_price, stock_quantity, low_stock_threshold, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)',
          [inv.id, inv.book_id, inv.name, inv.barcode || '', inv.unit, inv.purchase_price, inv.sale_price, inv.stock_quantity, inv.low_stock_threshold, inv.created_at]
        );
      }

      // Bulk Insert Cashbook
      for (const cb of archive.tables.cashbook || []) {
        await db.runAsync(
          'INSERT INTO cashbook (id, book_id, amount, type, category, entry_date, description, payment_mode, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)',
          [cb.id, cb.book_id, cb.amount, cb.type, cb.category, cb.entry_date, cb.description || '', cb.payment_mode || 'CASH', cb.created_at]
        );
      }

      // Bulk Insert Staff & Attendance
      for (const s of archive.tables.staff || []) {
        await db.runAsync(
          'INSERT INTO staff (id, book_id, name, phone, role, wage_type, wage_amount, joining_date) VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
          [s.id, s.book_id, s.name, s.phone, s.role, s.wage_type, s.wage_amount, s.joining_date]
        );
      }
      for (const sa of archive.tables.staff_attendance || []) {
        await db.runAsync(
          'INSERT INTO staff_attendance (id, staff_id, date, status, overtime_hours) VALUES (?, ?, ?, ?, ?)',
          [sa.id, sa.staff_id, sa.date, sa.status, sa.overtime_hours]
        );
      }
    });

    // 5. Restore Media Attachments to DocumentDirectory
    let restoredAttachments = 0;
    if (archive.attachments && archive.attachments.length > 0) {
      const attachmentsDir = `${FileSystem.documentDirectory}attachments/`;
      await FileSystem.makeDirectoryAsync(attachmentsDir, { intermediates: true });
      for (const att of archive.attachments) {
        try {
          await FileSystem.writeAsStringAsync(`${attachmentsDir}${att.filename}`, att.base64, {
            encoding: FileSystem.EncodingType.Base64,
          });
          restoredAttachments++;
        } catch (e) {
          console.warn(`Failed to restore attachment ${att.filename}:`, e);
        }
      }
    }

    return {
      success: true,
      message: 'All books, customers, bills, transactions, and media attachments restored successfully!',
      counts: {
        books: archive.tables.books?.length || 0,
        customers: archive.tables.customers?.length || 0,
        transactions: archive.tables.transactions?.length || 0,
        bills: archive.tables.bills?.length || 0,
        cashbook: archive.tables.cashbook?.length || 0,
        staff: archive.tables.staff?.length || 0,
        attachments: restoredAttachments,
      },
    };
  }
}
